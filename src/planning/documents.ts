import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ARCHITECTURE_SECTIONS, type Architecture, type ReviewIssue } from './schemas.js';

/**
 * Renders the planning results as documents in the project repository:
 *   docs/adr/NNNN-<slug>.md          one Architecture Decision Record per decision
 *   docs/architecture/ARCHITECTURE.md technical specification per area + Mermaid diagrams
 *   docs/research/RESEARCH.md         research findings with sources, verified vs assumption
 *   docs/planning/PLAN-REVIEW.md      planning review findings
 * Managed workspaces get a commit; an owner's existing repository is only written to (never committed to).
 */
export interface AdrRecord {
  adrId: string;
  number: number;
  title: string;
  status: string;
  context: string;
  decision: string;
  alternatives: string[];
  rationale: string;
  consequences: string;
  significant: boolean;
  decidedAt: number;
}
export interface FindingRecord {
  findingId: string;
  area: string;
  statement: string;
  kind: string;
  claimedKind: string;
  confidence: string;
  sources: { title: string; url: string }[];
  citationCheck: string;
  researchedAt: number;
}

const slug = (s: string) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 50) || 'decision';
const day = (ms: number) => new Date(ms).toISOString().slice(0, 10);
const para = (s: string) => (s.trim() ? s.trim() : '_Not recorded._');

export const adrFileName = (a: AdrRecord) => `${String(a.number).padStart(4, '0')}-${slug(a.title)}.md`;

export function renderAdr(a: AdrRecord): string {
  return [
    `# ADR ${String(a.number).padStart(4, '0')}: ${a.title}`,
    '',
    `- **Status:** ${a.status}${a.significant ? ' (significant: requires owner review)' : ''}`,
    `- **Date:** ${day(a.decidedAt)}`,
    `- **ID:** ${a.adrId}`,
    '',
    '## Context',
    para(a.context),
    '',
    '## Decision',
    para(a.decision),
    '',
    '## Alternatives considered',
    a.alternatives.length ? a.alternatives.map((x) => `- ${x}`).join('\n') : '_None recorded._',
    '',
    '## Rationale',
    para(a.rationale),
    '',
    '## Consequences',
    para(a.consequences),
    '',
  ].join('\n');
}

const TITLES: Record<string, string> = {
  system: 'System architecture',
  database: 'Database architecture',
  backend: 'Backend architecture',
  frontend: 'Frontend architecture',
  api: 'API design',
  authentication: 'Authentication model',
  authorization: 'Authorization model',
  integration: 'Integration architecture',
  deployment: 'Deployment design',
  security: 'Security design',
  monitoring: 'Monitoring strategy',
};

export function renderArchitecture(title: string, arch: Architecture, adrs: AdrRecord[]): string {
  const out = [
    `# Architecture: ${title}`,
    '',
    '_Generated by the planning workflow; decisions are recorded as ADRs in docs/adr._',
    '',
  ];
  for (const s of ARCHITECTURE_SECTIONS) {
    out.push(`## ${TITLES[s]}`, para(arch.sections?.[s] ?? ''), '');
  }
  out.push(
    '## Components',
    ...arch.components.map(
      (c) => `- **${c.name}**: ${c.responsibility} (requirements: ${c.requirementIds.join(', ')})`,
    ),
    '',
  );
  out.push(
    '## Technology',
    ...(arch.technology.length
      ? arch.technology.map((t) => `- **${t.area}**: ${t.choice} - ${t.rationale}`)
      : ['_None recorded._']),
    '',
  );
  out.push('## Data model', para(arch.dataModel), '');
  if (arch.diagrams.length) {
    out.push('## Diagrams');
    for (const d of arch.diagrams) out.push('', `### ${d.title}`, '', '```mermaid', d.mermaid.trim(), '```');
    out.push('');
  }
  out.push(
    '## Decision records',
    ...adrs.map(
      (a) =>
        `- [ADR ${String(a.number).padStart(4, '0')}](../adr/${adrFileName(a)}) ${a.title} (${a.status})`,
    ),
    '',
  );
  return out.join('\n');
}

export function renderResearch(title: string, findings: FindingRecord[], openQuestions: string[]): string {
  const out = [
    `# Research: ${title}`,
    '',
    'Findings are **verified** only when every cited source was actually retrieved by the research session (checked',
    'against the recorded web-tool evidence). Everything else is an **assumption** and must be confirmed before it is relied on.',
    '',
    '| ID | Area | Kind | Confidence | Statement | Sources | Citation check |',
    '| --- | --- | --- | --- | --- | --- | --- |',
  ];
  for (const f of findings) {
    const src = f.sources.map((s) => `[${s.title.replace(/[|\]]/g, ' ')}](${s.url})`).join('<br>') || '-';
    out.push(
      `| ${f.findingId} | ${f.area} | ${f.kind}${f.claimedKind !== f.kind ? ` (claimed ${f.claimedKind})` : ''} | ${f.confidence} | ${f.statement.replace(/\|/g, '\\|').replace(/\n/g, ' ')} | ${src} | ${f.citationCheck} |`,
    );
  }
  if (openQuestions.length) out.push('', '## Open research questions', ...openQuestions.map((q) => `- ${q}`));
  out.push('', `_Researched ${findings[0] ? day(findings[0].researchedAt) : '-'}._`, '');
  return out.join('\n');
}

export function renderReview(
  rounds: { round: number; source: string; verdict: string; issues: ReviewIssue[] }[],
): string {
  const out = ['# Planning review', ''];
  for (const r of rounds) {
    out.push(`## Round ${r.round} - ${r.source} review: ${r.verdict}`, '');
    if (!r.issues.length) out.push('_No issues._', '');
    for (const i of r.issues)
      out.push(
        `- **[${i.severity}] ${i.category}** (${i.id}): ${i.description}${i.recommendation ? ` _Fix:_ ${i.recommendation}` : ''}`,
      );
    out.push('');
  }
  return out.join('\n');
}

/** Write files below the repo (paths are fixed by this module, never model-chosen) and commit them if managed. */
export function writeProjectDocs(
  repoPath: string,
  files: Record<string, string>,
  opts: { commit: boolean; message: string },
): { written: string[]; committed: boolean } {
  const written: string[] = [];
  for (const [rel, content] of Object.entries(files)) {
    if (rel.includes('..') || path.isAbsolute(rel))
      throw new Error(`refusing to write outside the repo: ${rel}`);
    const abs = path.join(repoPath, rel);
    mkdirSync(path.dirname(abs), { recursive: true });
    writeFileSync(abs, content);
    written.push(rel);
  }
  let committed = false;
  if (opts.commit && existsSync(path.join(repoPath, '.git'))) {
    const git = (args: string[]) =>
      execFileSync('git', ['-c', 'user.name=ELEVARIQ Agent', '-c', 'user.email=agent@localhost', ...args], {
        cwd: repoPath,
        stdio: ['ignore', 'pipe', 'pipe'],
        windowsHide: true,
        timeout: 30_000,
      });
    try {
      git(['add', '--', ...written]);
      // --no-verify: the workspace is model-writable, so its .git/hooks must never run from the supervisor.
      git(['commit', '-q', '--no-verify', '-m', opts.message, '--', ...written]);
      committed = true;
    } catch {
      committed = false; // nothing to commit (identical content) or git unavailable: files are still on disk
    }
  }
  return { written, committed };
}
